"""Build-selected mod diagnostics policy shared by frozen apps and both ZIP formats."""
from pathlib import Path
import re
import shutil

MODULES = "lua/ge/extensions/beamngEarth/"
BUILDINFO = MODULES + "buildinfo.lua"
CAPTURE_PROVIDER = MODULES + "diagnostics_capture.lua"
FACADE = MODULES + "diagnostics.lua"
NOOP_PROVIDER = MODULES + "diagnostics_noop.lua"


def is_dev(ver):
    """Match the client devbuild.lua rule, including both -dev.N and .dev.N suffixes."""
    return isinstance(ver, str) and re.search(r"[.-]dev\.\d+$", ver, re.ASCII) is not None


def buildinfo(ver):
    enabled = "true" if is_dev(ver) else "false"
    return ("-- Generated by packaging; source-tree metadata is never changed.\n"
            f"return {{ devDiagnostics = {enabled} }}\n").encode("ascii")


def include_file(relative, ver):
    return str(relative).replace("\\", "/") != CAPTURE_PROVIDER or is_dev(ver)


def file_bytes(source, relative, ver):
    """Return one included payload file, replacing only generated build metadata."""
    if not include_file(relative, ver):
        raise ValueError("capture provider is excluded from stable packages")
    if str(relative).replace("\\", "/") == BUILDINFO:
        return buildinfo(ver)
    return Path(source).read_bytes()


def validate_source(source, ver):
    """An incomplete provider set must fail packaging, not break the installed client."""
    required = [BUILDINFO, FACADE, NOOP_PROVIDER]
    if is_dev(ver):
        required.append(CAPTURE_PROVIDER)
    for relative in required:
        path = Path(source) / relative
        if not path.is_file():
            raise FileNotFoundError(f"missing mod diagnostics component: {path}")


def stage_mod(source, destination, ver):
    """Copy a fresh frozen-app payload without mutating source or reusing stale staged files."""
    source, destination = Path(source).resolve(), Path(destination).resolve()
    if destination == source or destination.is_relative_to(source):
        raise ValueError("mod staging must be outside the source tree")
    validate_source(source, ver)

    def excluded(directory, names):
        relative = Path(directory).relative_to(source)
        return [name for name in names if not include_file((relative / name).as_posix(), ver)]

    # copytree requires a new destination: a previous dev stage cannot leak into a stable stage.
    shutil.copytree(source, destination, ignore=excluded)
    (destination / BUILDINFO).write_bytes(buildinfo(ver))
    return destination
